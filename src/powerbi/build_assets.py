"""Generate Power BI supporting assets from the star-schema CSVs.

Run (after ``python -m src.feature_engineering.star_schema``):
    python -m src.powerbi.build_assets

Writes:
* powerbi/power_query/*.m           - one typed M query per model table + parameter
* powerbi/theme/support_analytics_theme.json - importable report theme
* powerbi/validation/expected_kpi_values.csv - KPI values to validate DAX against
"""
from __future__ import annotations

import json

import pandas as pd

from src import config
