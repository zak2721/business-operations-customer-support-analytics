PBI = config.PROJECT_ROOT / "powerbi"
STAR = config.PROCESSED_DIR / "powerbi"
DATETIME_COLS = {"ticket_created_date", "first_response_date", "resolved_date", "feedback_date"}
DATE_COLS = {"Date", "MonthStart", "created_date", "resolved_date_only", "feedback_date_only", "operation_date",
             "performance_date", "cost_date", "hire_date", "registration_date"}
CURRENCY_HINTS = ("cost", "budget", "lifetime_value")


def m_type(col: str, s: pd.Series) -> str:
    if col in DATETIME_COLS:
        return "type datetime"
    if col in DATE_COLS:
        return "type date"
    if pd.api.types.is_bool_dtype(s):
        return "type logical"
    if pd.api.types.is_integer_dtype(s) or (pd.api.types.is_float_dtype(s) and s.dropna().apply(float.is_integer).all()
                                            and col.startswith(("is_", "sla_met", "satisfaction", "customer_rating",
                                                                "escalation", "reopened", "category_key", "channel_key",
                                                                "priority_key", "process_key", "created_hour"))):
        return "Int64.Type"
    if pd.api.types.is_float_dtype(s):
        return "Currency.Type" if any(h in col for h in CURRENCY_HINTS) and "per" not in col else "type number"
    return "type text"


def build_power_query() -> list[str]:
    out_dir = PBI / "power_query"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "00_DataFolder_parameter.m").write_text(
        '// Parameter: folder containing the star-schema CSVs (data/processed/powerbi/).\n'
        '// Create via Home > Manage Parameters > New, Type = Text, then paste as the value.\n'
        '"C:\\\\Projects\\\\business-operations-customer-support-analytics\\\\data\\\\processed\\\\powerbi\\\\" '
        'meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = true]\n')
    names = []
    for f in sorted(STAR.glob("*.csv")):
        df = pd.read_csv(f, nrows=5000, low_memory=False)
        types = ",\n        ".join(f'{{"{c}", {m_type(c, df[c])}}}' for c in df.columns)
        body = f"""// {f.stem} — generated by src/powerbi/build_assets.py from {f.name}
// Grain/keys: see powerbi/data_model.md
let
    Source   = Csv.Document(File.Contents(DataFolder & "{f.name}"),
                            [Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),
    Promoted = Table.PromoteHeaders(Source, [PromoteAllScalars = true]),
    Typed    = Table.TransformColumnTypes(Promoted, {{
        {types}
    }}, "en-US")
in
    Typed
"""
        (out_dir / f"{f.stem}.m").write_text(body)
        names.append(f.stem)
    return names


